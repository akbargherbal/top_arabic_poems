# إني ذكرتك بالزهراء مشتاقا - ابن زيدون (بحر البسيط)
#
# نسخة مُشَكَّلة تشكيلاً كاملاً (كل حرف)، أُعِدَّت خصيصاً لتكون صالحة
# للنطق/الغناء الآلي، عبر الخطوات التالية:
#   1) جمع النص من عدة مصادر (aldiwan.net/poem11858، mawdoo3، adabworld،
#      poetspedia، وغيرها) ومقارنتها للتأكد من ثبات الألفاظ والترتيب.
#   2) تحديد البحر: بحر البسيط (مُستَفعِلُن فاعِلُن مُستَفعِلُن فاعِلُن) ×2،
#      كما تجمع عليه كل المصادر.
#   3) ضبط التشكيل بيتاً بيتاً اعتماداً على الإعراب والصرف (لا التشكيل
#      الآلي)، مع مراعاة حالات مثل: منع "الزهراء" من الصرف يزول بدخول "أل"
#      فتُجَرّ بالكسرة، كسر آخر الاسم الصحيح المضاف إلى ياء المتكلم
#      ("أَرَقِي"، "حَمْلِي")، خطاب المحبوبة بكاف المخاطبة المؤنثة طوال
#      القصيدة ("شَقَقْتِ" لا "شَقَقْتَ")، ضمّ ميم الجماعة/الإشباع في مواضع
#      الوصل العروضي ("ذِكْرَكُمُ"، "وَافَاكُمُ"، "سَلَوْتُمُ")، ومنع "وَسْنَان"
#      من الصرف (وزن فَعْلان الذي مؤنثه فَعْلى).
#   4) التحقق من كل بيت عروضياً بمكتبة pyarud (وزن baseet) كخطوة تحقّق أولية
#      لا نهائية، إذ إنها قد تُعطي إيجابيات/سلبيات خاطئة في مواضع الإشباع
#      العروضي وزحافات العروض والضرب، فرُوجعت تلك المواضع يدوياً بالرجوع
#      إلى قواعد العروض الفصيح بدل الاعتماد الأعمى على أداة آلية.
#
